#!/usr/bin/env python3
"""
Module 5: Génération de rapports PDF
"""

import os
from datetime import datetime

def generate_pdf_report(findings, cve_results, score_result):
    """Generate PDF report (HTML fallback)"""
    
    os.makedirs("reports", exist_ok=True)
    filename = f"reports/audit_report_{datetime.now().strftime('%Y%m%d_%H%M%S')}.html"
    
    html_content = f"""<!DOCTYPE html>
<html>
<head>
    <title>Linux Security Audit Report - PDF Version</title>
    <style>
        body {{
            font-family: Arial, sans-serif;
            margin: 20px;
        }}
        .container {{
            max-width: 1000px;
            margin: auto;
        }}
        h1 {{ color: #333; }}
        .score-box {{
            background: #667eea;
            color: white;
            padding: 20px;
            text-align: center;
            border-radius: 10px;
        }}
        .score {{ font-size: 48px; font-weight: bold; }}
        .finding {{
            border-left: 4px solid;
            margin: 10px 0;
            padding: 10px;
            background: #f9f9f9;
        }}
        .HIGH {{ border-color: #fd7e14; }}
        .MEDIUM {{ border-color: #ffc107; }}
        .LOW {{ border-color: #28a745; }}
        .fix-code {{
            background: #f4f4f4;
            padding: 5px;
            font-family: monospace;
            margin-top: 5px;
        }}
    </style>
</head>
<body>
    <div class="container">
        <h1>🔒 Linux Security Audit Report - PDF</h1>
        <p><strong>Date:</strong> {datetime.now().strftime('%Y-%m-%d %H:%M:%S')}</p>
        
        <div class="score-box">
            <div class="score">Score: {score_result['score']}/100</div>
            <div>Grade: {score_result['grade']}</div>
        </div>
        
        <h2>Security Findings</h2>
"""
    
    for finding in findings:
        severity = finding.get('severity', 'LOW')
        html_content += f"""
        <div class="finding {severity}">
            <strong>{severity}: {finding.get('title', 'Issue')}</strong>
            <div class="fix-code">Fix: {finding.get('fix', 'No fix')}</div>
        </div>
"""
    
    html_content += f"""
        <h2>Recommendations</h2>
        <ul>
            <li>sudo ufw enable</li>
            <li>sudo chmod 600 /etc/crontab</li>
            <li>sudo apt update && sudo apt upgrade</li>
        </ul>
        <p>Generated by Linux Security Audit Framework</p>
        <p>Author: Nassim Ammar | PFA 2025-2026</p>
    </div>
</body>
</html>
"""
    
    with open(filename, 'w') as f:
        f.write(html_content)
    
    print(f"✅ PDF Report (HTML format): {filename}")
    return filename

if __name__ == "__main__":
    generate_pdf_report([{'title': 'Test', 'severity': 'HIGH', 'fix': 'sudo fix'}], [], {'score': 50, 'grade': 'D'})
